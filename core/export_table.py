"""
Export a heuristic as a precomputed integer table for ALL 20 goals, in the
three formats the friend's app can consume directly:

  heuristic_table.json   {goal: {city: h}}
  heuristicTable.ts      drop-in for ai-pathfinder-web/lib/routePath.ts  (getHeuristic)
  HeuristicTable.java    drop-in for ai-pathfinder-api (Map<String, Map<String,Integer>>)
"""
import json
import os
from romania_graph import CITIES


def export(builder, out_dir, name, description):
    table = {}
    for goal in CITIES:
        h = builder(goal)
        h = h[0] if isinstance(h, tuple) else h
        assert h[goal] == 0 and all(isinstance(h[c], int) and h[c] >= 0 for c in CITIES)
        table[goal] = {c: h[c] for c in CITIES}

    with open(os.path.join(out_dir, "heuristic_table.json"), "w", encoding="utf-8") as f:
        json.dump({"name": name, "description": description, "table": table}, f, indent=2)

    ts = [f"// {name}", f"// {description}", "// Generated by core/export_table.py -- do not edit by hand.",
          "// Usage in ai-pathfinder-web/lib/routePath.ts:",
          "//   import { getHeuristic } from './heuristicTable';   and delete the h(n)=0 placeholder.",
          "", "export const HEURISTIC: Record<string, Record<string, number>> = {"]
    for goal in CITIES:
        inner = ", ".join(f"'{c}': {table[goal][c]}" for c in CITIES)
        ts.append(f"  '{goal}': {{ {inner} }},")
    ts += ["};", "",
           "export function getHeuristic(node: string, goal: string): number {",
           "  return HEURISTIC[goal]?.[node] ?? 0;",
           "}", ""]
    with open(os.path.join(out_dir, "heuristicTable.ts"), "w", encoding="utf-8") as f:
        f.write("\n".join(ts))

    jv = ["package com.ceiromania.pathfinder.data;", "", "import java.util.Map;", "",
          "/**", f" * {name}", f" * {description}",
          " * Generated by core/export_table.py -- do not edit by hand.",
          " * TABLE.get(goal).get(city) = h(city) for that goal; h(goal) == 0.", " */",
          "public final class HeuristicTable {", "",
          "    public static final Map<String, Map<String, Integer>> TABLE = Map.ofEntries("]
    for i, goal in enumerate(CITIES):
        inner = ", ".join(f'"{c}", {table[goal][c]}' for c in CITIES)
        # Map.of supports up to 10 pairs, so use Map.ofEntries for the inner map too
        entries = ", ".join(f'Map.entry("{c}", {table[goal][c]})' for c in CITIES)
        jv.append(f'            Map.entry("{goal}", Map.ofEntries({entries})){"," if i < len(CITIES) - 1 else ""}')
    jv += ["    );", "",
           "    public static int h(String city, String goal) {", "        return TABLE.get(goal).get(city);", "    }", "",
           "    private HeuristicTable() {}", "}", ""]
    with open(os.path.join(out_dir, "HeuristicTable.java"), "w", encoding="utf-8") as f:
        f.write("\n".join(jv))
    return table
