"""
One call evaluates a heuristic (and its parameter variants) with every test in
the guide and writes results.md next to the experiment.

Usage from an experiment.py:

    from run_method import evaluate
    evaluate(
        method_name="Expected Goal Threat",
        variants={"beta=0.01 gamma=0.01": builder, ...},   # builder(goal) -> (h_int, raw) or h_int
        out_path=".../results.md",
        notes="free text shown at the top",
        main_variant="beta=0.01 gamma=0.01",               # gets the detailed tables
    )
"""
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from romania_graph import CITIES  # noqa: E402
from search import dijkstra  # noqa: E402
from baselines import BASELINES  # noqa: E402
import metrics as M  # noqa: E402
from report import md_table, fmt_path  # noqa: E402

DETAIL_GOALS = ("Bucharest", "Sibiu")


class _Memo:
    """Wraps builder(goal) so each goal is computed once; splits (h, raw)."""

    def __init__(self, builder):
        self.builder = builder
        self.cache = {}

    def _get(self, goal):
        if goal not in self.cache:
            r = self.builder(goal)
            if isinstance(r, tuple):
                h, raw = r
            else:
                h, raw = r, None
            for c in CITIES:
                if not isinstance(h[c], int):
                    raise TypeError(f"h({c}) = {h[c]!r} is not int -- use football_math.to_int_table")
            self.cache[goal] = (h, raw)
        return self.cache[goal]

    def h(self, goal):
        return self._get(goal)[0]

    def raw(self, goal):
        return self._get(goal)[1]


def summary_row(name, memo, run_all_pairs=True):
    pairs = M.pair_checks(memo.h)
    passed = sum(1 for p in pairs if p["pass"])
    dB, dS = dijkstra("Bucharest"), dijkstra("Sibiu")
    spB = M.spearman(memo.h("Bucharest"), dB)
    spS = M.spearman(memo.h("Sibiu"), dS)
    rk = M.all_goal_rank_summary(memo.h)
    fixed = M.astar_fixed(memo.h)
    fixed_opt = sum(1 for r in fixed if r["optimal"])
    fixed_exp = sum(r["expanded"] for r in fixed) / len(fixed)
    if run_all_pairs:
        ap = M.astar_all_pairs(memo.h)
        ap_opt, ap_exp = ap["optimal_pct"], ap["mean_expanded"]
    else:
        ap_opt = ap_exp = None
    return [name, f"{passed}/{len(pairs)}", spB, spS, rk["mean_spearman"], rk["min_spearman"],
            rk["mean_weighted_penalty"], f"{fixed_opt}/{len(fixed)}", fixed_exp, ap_opt, ap_exp]


SUMMARY_HEADERS = ["variant", "pair checks", "Spearman Buch", "Spearman Sibiu", "mean Spearman (20 goals)",
                   "min Spearman", "weighted inv. penalty", "A* optimal (10 fixed)", "mean expanded (fixed)",
                   "A* optimal % (380 pairs)", "mean expanded (380)"]


def evaluate(method_name, variants, out_path, notes="", main_variant=None, detail_goals=DETAIL_GOALS,
             run_all_pairs=True, include_baselines=True):
    t0 = time.time()
    memos = {name: _Memo(b) for name, b in variants.items()}
    main_variant = main_variant or next(iter(variants))
    lines = [f"# Results: {method_name}", "",
             "_Auto-generated by experiment.py. Do not edit; edit performance.md for interpretation._", ""]
    if notes:
        lines += [notes.strip(), ""]

    # ---- summary across variants + baselines
    lines += ["## Summary across variants", "",
              "Pair checks = guide Test 2 (8 obvious comparisons). Spearman = guide Test 4 (h vs true remaining cost; 1.0 = perfect ordering). "
              "Weighted inversion penalty = guide Test 5 (0 = no inversions, larger = worse; weighted by |d*(A)-d*(B)|). "
              "A* columns = guide Test 6.", ""]
    rows = [summary_row(n, m, run_all_pairs) for n, m in memos.items()]
    if include_baselines:
        for bname, bfn in BASELINES.items():
            rows.append(summary_row(f"_baseline: {bname}_", _Memo(bfn), run_all_pairs))
    lines += [md_table(SUMMARY_HEADERS, rows), ""]

    # ---- details for main variant
    memo = memos[main_variant]
    lines += [f"## Details for variant: {main_variant}", ""]

    lines += ["### Test 2 - obvious pairwise comparisons", ""]
    prow = [[p["goal"], f"{p['better']} ({p['d_better']})", f"{p['worse']} ({p['d_worse']})",
             p["h_better"], p["h_worse"], "tie" if p["tie"] else p["pass"]] for p in M.pair_checks(memo.h)]
    lines += [md_table(["goal", "closer city (d*)", "farther city (d*)", "h(closer)", "h(farther)", "h(closer) < h(farther)?"], prow), ""]

    for goal in detail_goals:
        h, raw = memo.h(goal), memo.raw(goal)
        d = dijkstra(goal)
        gs = M.goal_sanity(h, goal)
        lines += [f"### Goal = {goal}", "",
                  f"- Test 1 goal sanity: h({goal}) = {gs['h_goal']} ; is minimum: {gs['is_min']}",
                  f"- Test 4 Spearman(h, d*): **{M.spearman(h, d):.3f}**"]
        inv = M.inversions(h, d, goal)
        lines += [f"- Test 5 inversions: {inv['inversions']} of {inv['pairs']} pairs (ties: {inv['ties']}); weighted penalty **{inv['weighted_penalty']:.3f}**"]
        if inv["worst"]:
            lines += ["  - worst inversions (gap, closer, farther, d*closer, d*farther, h closer, h farther):"]
            for w in inv["worst"]:
                lines += [f"    - gap {w[0]}: {w[1]} (d*={w[3]}, h={w[5]}) ranked worse than {w[2]} (d*={w[4]}, h={w[6]})"]
        rd = M.ring_discrimination(h, goal)
        lines += ["- Ring discrimination (hop ring: cities / distinct h values): " +
                  ", ".join(f"ring {k}: {v[0]}/{v[1]}" for k, v in rd.items()), ""]
        lines += ["Test 3 - full table (sorted by true remaining cost):", ""]
        trows = []
        for r in M.full_table(h, raw, d, goal):
            rawv = "-" if r["raw"] is None else (f"{r['raw']:.4g}" if isinstance(r["raw"], float) else r["raw"])
            trows.append([r["city"], r["d_star"], rawv, r["h"], r["rank_d"], r["rank_h"], r["sensible"]])
        lines += [md_table(["city", "true remaining d*", "raw score", "h (int)", "rank by d*", "rank by h", "sensible (rank diff <= 3)"], trows), ""]

    lines += ["### Test 6 - A* on fixed start/goal pairs", ""]
    arows = [[f"{r['start']} -> {r['goal']}", r["cost"], r["optimal_cost"], r["optimal"], r["expanded"], fmt_path(r["path"])]
             for r in M.astar_fixed(memo.h)]
    lines += [md_table(["pair", "A* cost", "optimal cost", "optimal?", "nodes expanded", "path"], arows), ""]
    if run_all_pairs:
        ap = M.astar_all_pairs(memo.h)
        lines += [f"All 380 ordered pairs: optimal {ap['optimal']}/{ap['pairs']} ({ap['optimal_pct']:.1f}%), "
                  f"mean overshoot when not optimal {ap['mean_overshoot_when_wrong']:.1f}, mean nodes expanded {ap['mean_expanded']:.2f}."]
        if ap["worst"]:
            lines += ["", "Worst non-optimal results (overshoot, start, goal, A* cost, optimal):"]
            for w in ap["worst"]:
                lines += [f"- +{w[0]}: {w[1]} -> {w[2]} cost {w[3]} vs optimal {w[4]}"]
        lines += [""]

    # ---- baseline detail for reference (expanded counts on the fixed pairs)
    if include_baselines:
        lines += ["### Baselines on the same fixed pairs (nodes expanded)", ""]
        brows = []
        for bname, bfn in BASELINES.items():
            bm = _Memo(bfn)
            fr = M.astar_fixed(bm.h)
            brows.append([bname, f"{sum(1 for r in fr if r['optimal'])}/{len(fr)}",
                          ", ".join(str(r["expanded"]) for r in fr)])
        brows.append([f"this: {main_variant}", f"{sum(1 for r in arows if r[3])}/{len(arows)}",
                      ", ".join(str(r[4]) for r in arows)])
        lines += [md_table(["heuristic", "optimal", "expanded per pair (same order as table above)"], brows), ""]

    lines += [f"_Generated in {time.time() - t0:.1f}s._"]
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {out_path}")
    return memos


def print_table(h, goal, raw=None):
    """Quick console view of one table, sorted by h."""
    d = dijkstra(goal)
    print(f"goal={goal}")
    for c in sorted(CITIES, key=lambda c: (h[c], d[c])):
        extra = "" if raw is None else f"  raw={raw[c]:.4g}"
        print(f"  {c:16s} h={h[c]:5d}  d*={d[c]:4d}{extra}")
